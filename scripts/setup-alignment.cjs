execFileSync(python, ['-m', 'pip', 'install', '-r', path.join(root, 'server/requirements-alignment.txt')], { stdio: 'inherit' });
execFileSync(python, ['-m', 'pip', 'install', '--no-deps', 'qwen-asr==0.0.6'], { stdio: 'inherit' });
